/** Render the paired `frontier.weigh@1` report. Pure: the same rows always give the same text. */
import {
  OUTCOME_CLASSES,
  PROMOTION_RULE,
  summarize,
  type CaseResult,
  type PromotionVerdict,
  type Summary,
} from './score.ts';
import type { FrontierCase } from './build.ts';

export type JevStatus =
  | { readonly status: 'not_run'; readonly reason: string }
  | { readonly status: 'run'; readonly routed_unit: string; readonly run_id: string };

export interface ReportInput {
  readonly caseset: string;
  readonly digest: string;
  readonly cases: readonly FrontierCase[];
  readonly weighers: readonly { readonly id: string; readonly role: string }[];
  readonly results: readonly CaseResult[];
  readonly verdicts: readonly PromotionVerdict[];
  readonly jev: JevStatus;
}

const SHORT: Readonly<Record<string, string>> = {
  'goal.frame': 'frame',
  'report.review': 'review',
  'report.assemble': 'assemble',
  'goal.complete': 'complete',
};

export function shortKey(key: string): string {
  return key.startsWith('source.inspect:source:')
    ? `inspect ${key.slice('source.inspect:source:'.length)}`
    : (SHORT[key] ?? key);
}

function frontier(keys: readonly string[]): string {
  return keys.length === 0 ? '(none)' : keys.map(shortKey).join(', ');
}

export function summaryRow(summary: Summary): string {
  const counts = OUTCOME_CLASSES.map((name) => summary.outcomes[name]).join(' | ');
  const latency = summary.latency_p95_ms === null ? 'n/a' : `${summary.latency_p95_ms} ms`;
  return `| ${summary.weigher} | ${summary.split} | ${summary.n} | ${summary.covered} | ${summary.agreed}/${summary.n} = ${summary.agreement.toFixed(2)} | ${counts} | ${summary.completable} | ${summary.spent_total} | ${latency} |`;
}

export function verdictSection(verdict: PromotionVerdict): string {
  const lines = [`### ${verdict.weigher}: ${verdict.verdict}`, ''];
  for (const check of verdict.checks) {
    const mark = check.held === null ? 'n/a' : check.held ? 'held' : 'failed';
    lines.push(`- ${check.id} ${mark}: ${check.detail}`);
  }
  return lines.join('\n');
}

function jevSection(jev: JevStatus): string {
  if (jev.status === 'run') {
    return [
      '## Jev route',
      '',
      `Run \`${jev.run_id}\` through routed unit \`${jev.routed_unit}\`. Its rows above are live evidence for this case set and contract revision only.`,
    ].join('\n');
  }
  return [
    '## Jev route',
    '',
    `**Not run: \`${jev.reason}\`.** This is not a pass and not evidence either way. The Jev column is empty, no promotion verdict exists for it, and \`scripted@1\` stays the decision layer for \`frontier.weigh\`.`,
    '',
    'The live paired run needs:',
    '',
    '- `TYPESAFE_API_KEY` in `.env.local` (git-ignored) or the environment;',
    '- the route table (`weave.routes.json`, else `weave.routes.example.json`, with `weave.routes.local.json` overlaid) to name an `evaluate` / `score` unit on the `typesafe-ai` adapter and a `typesafe-jev` decision provider;',
    '- one run of `npm run bench:frontier-weigh` per contract revision and case-set digest; the command refuses a second live run over the same digest without `--rerun`, which must then be reported as a new experiment;',
    '- a reviewer pass over the paired holdout rows, recording any human correction before a promotion decision.',
  ].join('\n');
}

export function renderReport(input: ReportInput): string {
  const lines: string[] = [
    '# `frontier.weigh@1` paired comparison',
    '',
    'Generated by `npm run bench:frontier-weigh` (`benchmarks/frontier-weigh/run.ts`). Contract',
    '[`frontier.weigh@1`](../../packages/weave/src/FRONTIER-WEIGH-CONTRACT.md), view `profile.frontier-weigh@2`.',
    `Promotion rule \`${PROMOTION_RULE}\` and rubric \`frontier-weigh.rubric@1\` are stated in [README.md](README.md).`,
    '',
    `Case set \`${input.caseset}\` sha256 \`${input.digest}\`: ${input.cases.filter((c) => c.split === 'tune').length} tune, ${input.cases.filter((c) => c.split === 'holdout').length} holdout.`,
    '',
    '## Weighers',
    '',
    '| Weigher | Role |',
    '| --- | --- |',
    ...input.weighers.map((weigher) => `| ${weigher.id} | ${weigher.role} |`),
    `| jev | ${input.jev.status === 'run' ? `configured route \`${input.jev.routed_unit}\`` : `not run: \`${input.jev.reason}\``} |`,
    '',
    '## Results by split',
    '',
    'Agreement is the share of cases whose selected frontier equals the adjudicated one. A failed weighing counts as disagreement. `completable`: after the frontier, the actions remaining still cover the goal.',
    '',
    `| Weigher | Split | n | covered | agreement | ${OUTCOME_CLASSES.join(' | ')} | completable | spend (micros) | p95 latency |`,
    `| --- | --- | --- | --- | --- | ${OUTCOME_CLASSES.map(() => '---').join(' | ')} | --- | --- | --- |`,
  ];
  const ids = [...new Set(input.results.map((row) => row.weigher))];
  for (const split of ['tune', 'holdout'] as const) {
    for (const id of ids) {
      lines.push(summaryRow(summarize(input.results, id, split)));
    }
  }
  lines.push('', '## Promotion (holdout only)', '');
  lines.push('`scripted@1` is the baseline; the rule is applied to every other weigher against it.', '');
  for (const verdict of input.verdicts) {
    lines.push(verdictSection(verdict), '');
  }
  lines.push('## Paired holdout frontiers', '');
  lines.push("Each cell is the frontier Weave selected from that weigher's weights, then its outcome class.", '');
  const columns = [...ids.filter((id) => id !== 'jev'), 'jev'];
  lines.push(`| Case | Kind | Adjudicated | ${columns.join(' | ')} |`);
  lines.push(`| --- | --- | --- | ${columns.map(() => '---').join(' | ')} |`);
  for (const frontierCase of input.cases.filter((c) => c.split === 'holdout')) {
    const cells = columns.map((id) => {
      const row = input.results.find((r) => r.weigher === id && r.id === frontierCase.id);
      return row
        ? `${frontier(row.selected)} — ${row.outcome}`
        : id === 'jev' && input.jev.status === 'not_run'
          ? 'not run'
          : '—';
    });
    lines.push(
      `| ${frontierCase.id} | ${frontierCase.label.kind} | ${frontier(frontierCase.label.preferred)} | ${cells.join(' | ')} |`,
    );
  }
  lines.push('', '## Cost and correction tradeoff', '');
  lines.push(
    "A correction is a holdout case where a reviewer applying the rubric would change the selected frontier. No human correction has been recorded yet; these counts are the rubric's.",
    '',
  );
  lines.push(
    '| Weigher | Holdout corrections | Corrections avoided vs scripted@1 | Spend (micros) | Spend per avoided correction |',
  );
  lines.push('| --- | --- | --- | --- | --- |');
  const baseline = summarize(input.results, 'scripted@1', 'holdout');
  for (const id of ids) {
    const summary = summarize(input.results, id, 'holdout');
    const corrections = summary.n - summary.agreed;
    const avoided = summary.agreed - baseline.agreed;
    const per = avoided > 0 ? (summary.spent_total / avoided).toFixed(1) : 'n/a';
    lines.push(`| ${id} | ${corrections} | ${avoided} | ${summary.spent_total} | ${per} |`);
  }
  lines.push('', jevSection(input.jev), '');
  return lines.join('\n');
}
